export function getAdminDictionary(locale: Locale): AdminDictionary {
  return locale === "en" ? en : es;
}

/** Short date ("30 abr 2025" / "Apr 30, 2025") from an ISO date. */
export function fmtDate(locale: Locale, iso: string) {
  const [y, m, d] = iso.split("-").map(Number);
  const date = new Date(Date.UTC(y, m - 1, d));
  if (locale === "es") {
    const months = ["ene", "feb", "mar", "abr", "may", "jun", "jul", "ago", "sep", "oct", "nov", "dic"];
    return `${String(d).padStart(2, "0")} ${months[m - 1]} ${y}`;
  }
  return date.toLocaleDateString("en-US", { month: "short", day: "2-digit", year: "numeric", timeZone: "UTC" });
}

/** Short day label for chart axes ("1 abr" / "Apr 1"). */
export function fmtDay(locale: Locale, day: number) {
  return locale === "es" ? `${day} abr` : `Apr ${day}`;
}
